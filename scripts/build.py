#!/usr/bin/env python3
"""Deterministic README, machine catalog, and static-site generator."""
import argparse
from collections import Counter
import html
import json
from pathlib import Path
from common import ROOT, KINDS, CATEGORIES, load_catalog, locales, read_yaml, review
from validate import validate

REPO = "https://github.com/OWNER/awesome-grok-bot"
LICENSES = {"CC0-1.0": "https://creativecommons.org/publicdomain/zero/1.0/", "CC-BY-4.0": "https://creativecommons.org/licenses/by/4.0/"}


def md(value):
    return html.escape(str(value), quote=False).replace("|", "&#124;").replace("[", "&#91;").replace("]", "&#93;").replace("\n", " ")


def readme(lang, ui, data, translations, picks):
    name = lambda code: "README.md" if code == "en" else f"README.{code}.md"
    out = ["<!-- Generated by scripts/build.py. Edit data/*.yaml and i18n/*.yaml. -->", "# awesome Grok Bot", "", ui["readme_intro"], "", " · ".join(f'[{v["language_name"]}]({name(k)})' for k, v in translations.items()), "", f'[{ui["browse"]}](https://OWNER.github.io/awesome-grok-bot/) · [{ui["contribute"]}](CONTRIBUTING.md) · [JSON](dist/catalog.json) · [llms.txt](llms.txt)', "", " | ".join(f'{len(data[k])} {ui["kinds"][k]}' for k in KINDS), "", f'## {ui["policy"]}', "", ui["policy_text"], "", f'## {ui["weekly"]}', ""]
    lookup = {e["id"]: e for entries in data.values() for e in entries}
    if picks:
        for p in sorted(picks, key=lambda x: x["week"], reverse=True):
            out += [f'### {p["week"]}', ""]
            out += [f'- [{md(lookup[i]["name"])}]({lookup[i]["url"]}) — {md(review(lookup[i], lang))}' for i in p["entries"]]
            out += [""]
    else:
        out += [ui["picks_empty"], "", ui["picks_text"], ""]
    for cat in CATEGORIES:
        entries = sorted((e for e in lookup.values() if e["category"] == cat), key=lambda e: (e["name"].casefold(), e["id"]))
        out += [f'## {ui["categories"][cat]}', "", f'| {ui["resources"]} | {ui["review"]} | {ui["author"]} | {ui["tier"]} | {ui["source"]} / {ui["license"]} | {ui["checked"]} |', '| --- | --- | --- | --- | --- | --- |']
        for e in entries:
            s = e["source"]
            credit = f'[{md(s["repo"])}](https://github.com/{s["repo"]}) · [{s["license"]}]({LICENSES[s["license"]]})'
            if s["license"] == "CC-BY-4.0":
                credit += f'<br>{md(s["attribution"])}. {md(s["changes"])}'
            out.append(f'| [{md(e["name"])}]({e["url"]}) | {md(review(e, lang))} | {md(e["author"]["name"])} | {ui[e["tier"]]} | {credit} | {e["last_checked"]} |')
        out += [""]
    out += [f'## {ui["data_title"]}', "", ui["data_text"], "", f'## {ui["quickstart"]}', "", "```sh", "python3 -m venv .venv", "source .venv/bin/activate", "pip install -r requirements.txt", "python scripts/validate.py", "python scripts/build.py", "python scripts/build.py --check", "python scripts/check_links.py --dry-run", "python -m unittest discover -s tests", "python -m http.server 8000 --directory site", "```", "", f'## {ui["badge_title"]}', "", ui["badge_text"], "", '![awesome Grok Bot featured author](badges/featured.svg)', "", "```md", f'[![Featured on awesome Grok Bot]({REPO}/raw/main/badges/featured.svg)]({REPO})', "```", "", f'## {ui["license_title"]}', "", ui["license_text"], "", '[LICENSE](LICENSE) · [LICENSE-DATA](LICENSE-DATA) · [CREDITS](CREDITS.md)', "", ui["independent"], ""]
    return "\n".join(out)


def outputs(root=ROOT):
    validate(root)
    data, ui = load_catalog(root), locales(root)
    picks = read_yaml(root / "data/picks.yaml")
    entries = [{**e, "kind": kind} for kind in KINDS for e in sorted(data[kind], key=lambda x: x["id"])]
    catalog = {"name": "awesome Grok Bot", "repository": REPO, "schema_version": 1, "last_checked": max((e["last_checked"] for e in entries), default=None), "counts": {k: len(v) for k, v in data.items()}, "licenses": dict(sorted(Counter(e["source"]["license"] for e in entries).items())), "entries": entries, "picks": picks}
    dump = lambda x: json.dumps(x, ensure_ascii=False, indent=2) + "\n"
    out = {"dist/catalog.json": dump(catalog), "site/data/catalog.json": dump(catalog), "site/data/ui.json": dump(ui), "site/.nojekyll": ""}
    for lang, strings in ui.items():
        out["README.md" if lang == "en" else f"README.{lang}.md"] = readme(lang, strings, data, ui, picks)
    lines = ["# awesome Grok Bot", "", "> An independent curated directory of Grok Bot shares, skills, MCP connectors, and guides.", "", "All seed entries are listed, not workflow-tested. HTTP reachability is not an endorsement.", "Metadata license is per entry; linked resources retain their own licenses.", "", "## Resources", ""]
    for e in entries:
        s = e["source"]
        lines.append(f'- [{e["name"]}]({e["url"]}): {e["review"]} Author: {e["author"]["name"]}. Tier: {e["tier"]}. Checked: {e["last_checked"]}. Source: https://github.com/{s["repo"]}; {s["license"]} ({LICENSES[s["license"]]}).' + (f' Attribution: {s["attribution"]}. Changes: {s["changes"]}' if "attribution" in s else ""))
    out["llms.txt"] = "\n".join(lines) + "\n"
    out["site/llms.txt"] = out["llms.txt"]
    for path in sorted((root / "web").rglob("*")):
        if path.is_file():
            out["site/" + str(path.relative_to(root / "web"))] = path.read_text(encoding="utf-8")
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on missing, stale, or extra generated files without writing")
    args = parser.parse_args()
    rendered = outputs()
    stale = [name for name, content in rendered.items() if not (ROOT / name).exists() or (ROOT / name).read_text(encoding="utf-8") != content]
    existing = [p for folder in ("site", "dist") for p in (ROOT / folder).rglob("*") if p.is_file()]
    existing += list(ROOT.glob("README.*.md"))
    extras = [p for p in existing if str(p.relative_to(ROOT)) not in rendered]
    if args.check:
        if stale or extras:
            print("Generated output drift:", *stale, *(str(p.relative_to(ROOT)) for p in extras), sep="\n")
            return 1
        print("Generated outputs are current.")
        return 0
    for name, content in rendered.items():
        path = ROOT / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for path in extras:
        path.unlink()
    print(f"Built {len(rendered)} files from {sum(len(v) for v in load_catalog().values())} entries.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
